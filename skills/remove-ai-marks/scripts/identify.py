# Ported from wiltodelta/remove-ai-watermarks src/remove_ai_watermarks/identify.py (ProvenanceReport verdict fields and the collect -> record -> judge pipeline), Apache-2.0; modified: attribution is adapted to this repo's findings vocabulary and typed probes, the verdict is exactly the six contract fields (upstream's confidence/watermarks/signals/caveats lists are not adopted), the "nothing to do" exit code is not adopted, and the judge never opens a file or runs a classifier
"""Aggregate collected provenance evidence into one tri-state verdict.

The pipeline is evidence-record based: ``collect_provenance_record`` touches
the file once, this module judges the record — so the verdict from a JSON
round-trip of the record equals the verdict from the file, and the judge
never re-opens the source or runs a classifier.

THE TRI-STATE HONESTY CONTRACT

``is_ai_generated`` is ``True`` when evidence asserts AI provenance and
``None`` (unknown) when it does not. It is never ``False``: stripped or
absent metadata is not local proof of a clean origin. Signals and their
strengths:

- asserts AI from metadata (``ai_from_metadata=True``): a TC260 AIGC label,
  the xAI signature pair, an IPTC AI digital-source token, a known AI
  generator product in a generator field, C2PA evidence naming an AI tool or
  an asserts-AI issuer, or a structural AI metadata token (digitalSourceType,
  SynthID, AIGC) found inside a recognized metadata structure.
- asserts AI on weaker evidence (``ai_from_metadata=False``): the Samsung
  Galaxy AI editing marker, the Higgsfield job hint, or vendor-prose tokens
  in metadata — an editing/hosting hint, not generation provenance.
- C2PA presence alone (a caBX/JUMBF container, an issuer name) is provenance
  structure, not an AI assertion: cameras and neutral editors sign too.

``integrity_clashes`` is populated only from verified evidence: a TC260 label
whose ``SecurityData`` signature fails verification while the same label
asserts a content producer. ``c2pa_validation`` reports each validation
dimension (integrity, signature, signer trust/validity) as ``unknown`` unless
something verified it — the stdlib fallback never turns a hint into a clean
bill.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

if __package__ in (None, ""):
    pass

sys.path.insert(0, str(Path(__file__).resolve().parent))

from provenance_record import (
    PROVENANCE_RECORD_TYPE,
    require_record_version,
)

#: Stable contract for the serialized verdict (``ProvenanceVerdict.to_dict``).
PROVENANCE_VERDICT_SCHEMA_VERSION = 1

_PRODUCER_IN_FINDING = re.compile(r"ContentProducer=(\S+?) \(")

#: Tokens that structurally assert AI when found in a metadata structure.
_STRUCTURAL_AI_TOKENS = frozenset(
    token.casefold()
    for token in (
        "digitalSourceType",
        "trainedAlgorithmicMedia",
        "compositeWithTrainedAlgorithmicMedia",
        "SynthID",
        "AIGC",
        "aigc",
        "AI generated",
        "Generated by",
    )
)


@dataclass
class ProvenanceVerdict:
    """The six-field provenance verdict for one file."""

    is_ai_generated: bool | None  # True / None (unknown); False is never produced
    platform: str | None
    ai_source_kind: str | None  # "generated" | "enhanced" | None
    ai_from_metadata: bool
    integrity_clashes: list[str] = field(default_factory=list)
    c2pa_validation: dict[str, Any] | None = None

    def to_dict(self) -> dict[str, Any]:
        """The versioned, JSON-safe verdict contract (exactly six fields)."""
        return {
            "schema_version": PROVENANCE_VERDICT_SCHEMA_VERSION,
            "is_ai_generated": self.is_ai_generated,
            "platform": self.platform,
            "ai_source_kind": self.ai_source_kind,
            "ai_from_metadata": self.ai_from_metadata,
            "integrity_clashes": list(self.integrity_clashes),
            "c2pa_validation": self.c2pa_validation,
        }


def unknown_verdict() -> ProvenanceVerdict:
    """The all-unknown verdict: no signal anywhere, never a clean bill."""
    return ProvenanceVerdict(
        is_ai_generated=None,
        platform=None,
        ai_source_kind=None,
        ai_from_metadata=False,
        integrity_clashes=[],
        c2pa_validation=None,
    )


def _platform_for_tc260(producer: str) -> str | None:
    import tc260_verify

    row = tc260_verify.producer_for_code(producer)
    if row is None:
        return None
    return row.image_platform or row.vendor


def _tc260_platform(record_evidence: dict[str, Any]) -> str | None:
    """The registry-resolved platform for a collected TC260 label.

    The typed label is authoritative; the finding line's
    ``ContentProducer=<code> (<vendor>)`` field-aware format is the fallback
    for carriers the byte-scan cannot reach (PNG text chunks).
    """
    label = record_evidence.get("tc260_label")
    if isinstance(label, dict) and label.get("ContentProducer"):
        platform = _platform_for_tc260(str(label["ContentProducer"]))
        if platform is not None:
            return platform
    for finding in record_evidence.get("findings") or []:
        if "TC260 AIGC label" not in finding:
            continue
        match = _PRODUCER_IN_FINDING.search(finding)
        if match:
            platform = _platform_for_tc260(match.group(1))
            if platform is not None:
                return platform
    return None


def _c2pa_asserts_ai(c2pa_hints: dict[str, Any] | None) -> bool:
    """True when C2PA evidence names an AI tool or an asserts-AI issuer."""
    if not c2pa_hints:
        return False
    if c2pa_hints.get("ai_tools"):
        return True
    import c2pa_constants

    issuers = c2pa_hints.get("issuers") or []
    return any(org in c2pa_constants.C2PA_IDENTITY_AI_ORGS for org in issuers)


def _ai_hints_split(evidence: dict[str, Any]) -> tuple[bool, bool]:
    """``(structural_hit, prose_hit)`` among the collected AI hint tokens."""
    structural = False
    prose = False
    for token in evidence.get("ai_hints") or []:
        if token.casefold() in _STRUCTURAL_AI_TOKENS:
            structural = True
        else:
            prose = True
    return structural, prose


def _c2pa_validation(evidence: dict[str, Any]) -> dict[str, Any] | None:
    """The honest C2PA validation block: unknown until something verifies it."""
    c2pa_hints = evidence.get("c2pa_hints")
    has_c2pa = bool(evidence.get("has_c2pa"))
    if not has_c2pa and not c2pa_hints:
        return None
    if c2pa_hints and (c2pa_hints.get("claim_generator") is not None or c2pa_hints.get("found")):
        return {
            "source": "stdlib-cbor-fallback",
            "state": "hints-only",
            "integrity": "unknown",
            "signature": "unknown",
            "signer_trust": "unknown",
            "signer_validity": "unknown",
            "claim_generator": c2pa_hints.get("claim_generator"),
            "issuers": list(c2pa_hints.get("issuers") or []),
            "ai_tools": list(c2pa_hints.get("ai_tools") or []),
            "cbor": dict(c2pa_hints.get("cbor") or {}),
            "codes": [],
        }
    return {
        "source": "findings",
        "state": "unknown",
        "integrity": "unknown",
        "signature": "unknown",
        "signer_trust": "unknown",
        "signer_validity": "unknown",
        "codes": [],
    }


def _c2pa_platform(c2pa_hints: dict[str, Any] | None) -> str | None:
    if not c2pa_hints:
        return None
    platforms = c2pa_hints.get("claim_generator_platforms") or []
    return str(platforms[0]) if platforms else None


def identify_from_record(record: dict[str, Any]) -> ProvenanceVerdict:
    """Build the provenance verdict from a collected record.

    Accepts any mapping with the record's schema (a JSON round-trip
    included). Rejects unknown schema versions and foreign record types with
    ``UnsupportedRecordVersion`` / ``ValueError`` — a stable rejection, never
    a guessed verdict. The source file is never opened.
    """
    if not isinstance(record, dict):
        raise ValueError("provenance record must be a JSON object")
    require_record_version(record.get("schema_version"))
    if record.get("record_type") != PROVENANCE_RECORD_TYPE:
        raise ValueError(
            f"unexpected record_type {record.get('record_type')!r}; "
            f"expected {PROVENANCE_RECORD_TYPE!r}"
        )
    return _judge(record.get("evidence") or {})


def _judge(evidence: dict[str, Any]) -> ProvenanceVerdict:
    """Map collected evidence onto the six-field verdict."""
    findings = [str(f) for f in evidence.get("findings") or []]

    tc260_present = evidence.get("tc260_label") is not None or any(
        "TC260 AIGC label" in f for f in findings
    )
    signature = evidence.get("tc260_signature") or {}
    signature_failed = signature.get("status") == "failed" or any(
        "TC260 label signature does not verify" in f for f in findings
    )
    xai = bool(evidence.get("xai_pair")) or any("xAI/Grok provenance marker" in f for f in findings)
    iptc = evidence.get("iptc_digital_source") or None
    iptc_ai = iptc is not None
    generator_products = list(evidence.get("generator_products") or [])
    samsung = evidence.get("samsung_genai_type") is not None or any(
        "Samsung Galaxy AI marker" in f for f in findings
    )
    hf_job = evidence.get("hf_job_id") is not None or any("hf-job-id" in f for f in findings)
    structural_hint, prose_hint = _ai_hints_split(evidence)
    c2pa_hints = evidence.get("c2pa_hints") or None
    c2pa_ai = _c2pa_asserts_ai(c2pa_hints)

    ai_from_metadata = bool(
        tc260_present or xai or iptc_ai or generator_products or c2pa_ai or structural_hint
    )
    weak_ai = bool(samsung or hf_job or prose_hint)

    if ai_from_metadata or weak_ai:
        is_ai: bool | None = True
    else:
        is_ai = None  # absent evidence is unknown, never "clean"

    # Platform: the strongest registry attribution wins; set from provenance
    # evidence even when AI-ness stays unknown (a signed capture names its
    # signer), because the field records origin, not an accusation.
    platform = None
    if tc260_present:
        platform = _tc260_platform(evidence)
    if platform is None:
        platform = _c2pa_platform(c2pa_hints)
    if platform is None and generator_products:
        platform = generator_products[0]
    if platform is None and xai:
        platform = "xAI Grok"
    if platform is None and samsung:
        platform = "Samsung Galaxy AI"
    if platform is None and hf_job:
        platform = "Higgsfield"

    ai_source_kind = None
    if is_ai and iptc_ai:
        ai_source_kind = str(iptc.get("kind")) if iptc.get("kind") else None

    clashes: list[str] = []
    if signature_failed:
        producer = ""
        label = evidence.get("tc260_label")
        if isinstance(label, dict):
            producer = str(label.get("ContentProducer", ""))
        if not producer:
            for finding in findings:
                match = _PRODUCER_IN_FINDING.search(finding)
                if match:
                    producer = match.group(1)
                    break
        clashes.append(
            "TC260 label signature does not verify while the label asserts "
            f"ContentProducer={producer or '<unparsed>'} — provenance internally "
            "inconsistent (tampered or transplanted label)"
        )

    return ProvenanceVerdict(
        is_ai_generated=is_ai,
        platform=platform,
        ai_source_kind=ai_source_kind,
        ai_from_metadata=ai_from_metadata,
        integrity_clashes=clashes,
        c2pa_validation=_c2pa_validation(evidence),
    )


def identify_file(path: Path) -> ProvenanceVerdict:
    """Collect once from ``path`` and judge — the file-side entry point.

    Pure metadata evidence only: no optional external tools, no classifiers,
    no pixel decoding. Returns the all-unknown verdict shape for text assets
    and unscannable inputs; a failed collection is unknown, never clean.
    """
    from provenance_record import collect_provenance_record

    record = collect_provenance_record(Path(path))
    if record.get("status") == "error" and not record.get("evidence", {}).get("findings"):
        # An unreadable source has no evidence to judge; say unknown, not clean.
        return unknown_verdict()
    return identify_from_record(record)


def identify_from_json(payload: str | bytes) -> ProvenanceVerdict:
    """Judge a JSON-serialized record (the transport entry point)."""
    try:
        record = json.loads(payload)
    except (TypeError, ValueError) as error:
        raise ValueError(f"invalid provenance record JSON: {error}") from error
    return identify_from_record(record)


