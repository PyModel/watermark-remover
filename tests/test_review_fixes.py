@pytest.mark.parametrize(
    "author", [{"@type": "Person", "name": "Jane Smith"}, [{"name": "Jane Smith"}], None, 42]
)
def test_jsonld_provenance_keys_ignore_value_shape(author):
    text = (
        '<script type="application/ld+json">'
        + json.dumps({"author": author, "headline": "hello"})
        + "</script>"
    )
    cleaned = clean_html(text)[0]
    # The provenance key goes whatever its value shape; the payload survives.
    assert "Jane" not in cleaned and "author" not in cleaned
    assert "headline" in cleaned
    assert inspect_html(text)[1] is True


def test_jsonld_nested_provenance_and_escaped_key():
    text = (
        '<script type="application/ld+json">{"@graph":[{"a\\u0075thor":{"name":"Jane"}}]}</script>'
    )
    cleaned = clean_html(text)[0]
    # Escaped key is decoded by the JSON parser, so the provenance key is
    # still found and removed; the enclosing @graph survives, emptied of it.
    assert "Jane" not in cleaned
    assert "@graph" in cleaned
    assert inspect_html(text)[1] is True


def test_jsonld_plain_content_preserved():
    text = '<script type="application/ld+json">{"description":"author: Jane","headline":"hello"}</script>'
    assert clean_html(text)[0] == text
    assert not inspect_html(text)[1]


@pytest.mark.parametrize("marker", ["ChatGPT", "c2pa"])
def test_html_comment_inspection_matches_clean(marker):
    text = f"<body><!-- generated by {marker} -->hello</body>"
    c2pa, ai, findings, _, _ = inspect_html(text)
    assert ai and findings
    assert c2pa == (marker == "c2pa")
    assert "<!--" not in clean_html(text)[0]
    assert not inspect_html(clean_html(text)[0])[1]


def test_html_raw_text_comment_not_reported():
    text = '<script>const s="<!-- generated by ChatGPT -->";</script>'
    assert not inspect_html(text)[1]
    assert clean_html(text)[0] == text


def _subifd_array(*, big=False, bo="<", marker=True):
    off_fmt = bo + ("Q" if big else "I")
    count_fmt = bo + ("Q" if big else "H")
    off_len, count_len, entry_size, header_size = (8, 8, 20, 16) if big else (4, 2, 12, 8)
    block_size = count_len + entry_size + off_len
    pointer_array = header_size + block_size
    # Three pointers forces out-of-line storage even for BigTIFF LONG entries.
    ptrs = [pointer_array + 12 + i * block_size for i in range(3)]
    payload_start = pointer_array + 12 + 3 * block_size
    payloads = [(f"OpenAI {i}" if marker else f"camera {i}").encode() + b"\0" for i in range(3)]

    def entry(tag, typ, count, value):
        return (
            struct.pack(bo + "HH", tag, typ)
            + struct.pack(off_fmt, count)
            + struct.pack(off_fmt, value)
        )

    signature = b"II" if bo == "<" else b"MM"
    header = (
        signature
        + (struct.pack(bo + "HHH", 43, 8, 0) if big else struct.pack(bo + "H", 42))
        + struct.pack(off_fmt, header_size)
    )
    root = struct.pack(count_fmt, 1) + entry(330, 4, 3, pointer_array) + struct.pack(off_fmt, 0)
    subdirs = bytearray()
    position = payload_start
    for payload in payloads:
        subdirs += (
            struct.pack(count_fmt, 1)
            + entry(270, 2, len(payload), position)
            + struct.pack(off_fmt, 0)
        )
        position += len(payload)
    return (
        header + root + struct.pack(bo + "III", *ptrs) + bytes(subdirs) + b"".join(payloads),
        pointer_array,
        ptrs,
    )


@pytest.mark.parametrize("big", [False, True])
@pytest.mark.parametrize("bo", ["<", ">"])
def test_tiff_subifd_array_all_payloads_removed(big, bo):
    data, pointer_array, _ = _subifd_array(big=big, bo=bo)
    assert inspect_tiff(data)[1]
    cleaned, actions = strip_tiff(data)
    assert b"OpenAI" not in cleaned
    assert cleaned[pointer_array : pointer_array + 12] == bytes(12)
    assert any(action.params.get("tag") == 330 for action in actions)
    assert len(cleaned) == len(data)


@pytest.mark.parametrize("big", [False, True])
def test_tiff_selective_subifd_array_keeps_benign_payloads(big):
    data, _, _ = _subifd_array(big=big, marker=False)
    assert strip_tiff(data, strip_all_metadata=False)[0] == data


def test_tiff_selective_subifd_array_removes_marked_payloads():
    data, _, _ = _subifd_array()
    assert b"OpenAI" not in strip_tiff(data, strip_all_metadata=False)[0]


def test_launcher_reinstalls_old_or_partial_dependencies(tmp_path, monkeypatch):
    source = tmp_path / "tui"
    (source / "src").mkdir(parents=True)
    (source / "src/index.ts").write_text("")
    (source / "package.json").write_text('{"dependencies":{"@earendil-works/pi-tui":"1.0.2"}}')
    (source / "bun.lock").write_text("lock v1")
    (source / "node_modules/@opentui/core").mkdir(parents=True)
    calls = []

    def install(directory, bun):
        calls.append(directory)
        dependency = directory / "node_modules/@earendil-works/pi-tui"
        dependency.mkdir(parents=True, exist_ok=True)
        (dependency / "package.json").write_text("{}")
        return 0

    monkeypatch.setattr(tui, "_install", install)
    assert tui.prepare_frontend(source, "bun") == (source, 0)
    assert len(calls) == 1
    assert tui.prepare_frontend(source, "bun") == (source, 0)
    assert len(calls) == 1
    (source / "bun.lock").write_text("lock v2")
    assert tui.prepare_frontend(source, "bun") == (source, 0)
    assert len(calls) == 2


def test_launcher_failed_install_retries(tmp_path, monkeypatch):
    (tmp_path / "src").mkdir()
    (tmp_path / "src/index.ts").write_text("")
    (tmp_path / "package.json").write_text('{"dependencies":{}}')
    (tmp_path / "bun.lock").write_text("lock")
    (tmp_path / "node_modules").mkdir()
    calls = []
    monkeypatch.setattr(tui, "_install", lambda *args: calls.append(args) or 1)
    assert tui.prepare_frontend(tmp_path, "bun") == (None, 1)
    assert tui.prepare_frontend(tmp_path, "bun") == (None, 1)
    assert len(calls) == 2
